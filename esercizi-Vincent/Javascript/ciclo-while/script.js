let cont = 1;

/*con el ciclo while, la condicion sera verificada siempre que sea verdadera,
 cuando se vuelva falsa entonces se saldra del bucle en este caso contara hasta que llegue a ser menor o igual a 100*/
while (cont <= 100) {
document.write(cont);

cont++; // aqui porque se necesita repetir el bucle y aqui agregamos al contador despues del resultado escrito en cont
};

//con while se verifica la condicion despues de ejecutar por ejemplo en este caso primero se ejecuta el document.write y luego se verifica la condicion
