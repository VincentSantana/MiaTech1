// Dichiarare variabili di diversi tipi
const numero = 42;
const stringa = 'Ciao Manfredi!';
const array = [1, 2, 3, 4, 5];
const oggetto = { nome: 'Vincent', cognome: 'Santana' };

// Stampare le variabili nella console
console.log('Numero:', numero);
console.log('Stringa:', stringa);
console.log('Array:', array);
console.log('Oggetto:', oggetto);

// Stampare il tipo di dato di ogni variabile
console.log('Tipo di numero:', typeof numero);
console.log('Tipo di stringa:', typeof stringa);
console.log('Tipo di array:', Array.isArray(array));
console.log('Tipo di oggetto:', typeof oggetto);